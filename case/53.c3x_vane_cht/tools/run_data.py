def validate(name, rows):
    s = [r[0] for r in rows]
    i_stag = min(range(len(s)), key=lambda k: s[k])
    ps, ss = s[:i_stag + 1], s[i_stag:]
    err = []
    if any(ps[k] <= ps[k + 1] for k in range(len(ps) - 1)):
        err.append("正圧面の s/S が降順でない")
    if any(ss[k] >= ss[k + 1] for k in range(len(ss) - 1)):
        err.append("負圧面の s/S が昇順でない")
    miss_t = miss_h = 0
    for k, (a, b, t, h) in enumerate(rows, 1):
        if not (0.0 <= a <= 1.0 and 0.0 <= b <= 1.0):
            err.append(f"行 {k}: 位置が [0,1] の外 ({a}, {b})")
        # **判読不能セルは None** (スキャンが 2 値で復元できない箇所)。推測で埋めない。
        if t is None:
            miss_t += 1
        elif not (0.5 <= t <= 0.9):
            err.append(f"行 {k}: 正規化壁温 {t} が 0.5-0.9 の外")
        if h is None:
            miss_h += 1
        elif not (0.2 <= h <= 1.0):
            err.append(f"行 {k}: 正規化熱伝達係数 {h} が 0.2-1.0 の外")
    if miss_t + miss_h:
        frac = (miss_t + miss_h) / (2.0 * len(rows))
        if frac > 0.15:
            err.append(f"判読不能セルが {100*frac:.0f} % (15 % 超は転記をやり直す)")
    print(f"[{name}] {len(rows)} rows, stagnation at row {i_stag + 1} (s/S={s[i_stag]}), "
          f"missing Tw {miss_t} / h {miss_h}, {'OK' if not err else 'NG'}")
    if err:
        for e in err[:10]:
            print("   -", e)
        sys.exit(f"[{name}] 転記の検査に失敗")


def main():
    for name, t in TABLES.items():
        validate(name, t["rows"])
        p = ROOT / t["out"]
        p.parent.mkdir(parents=True, exist_ok=True)
        with open(p, "w") as f:
            f.write(f"# {t['vane']} {name} (code {t['code']}, M2={t['M2']}) — NASA CR-168015 Appendix A, "
                    f"{t['page']}\n"
                    f"# 転記元はページ画像 (OCR は桁落ちするため使わない)。Tw = Tw_norm * {t['Tref']} K\n"
                    "# 空欄 = スキャン (300 dpi 2 値) で判読不能。推測で埋めていない\n"
                    "# 並び: 正圧面 (後縁->前縁) のあと 負圧面 (前縁->後縁)\n"
                    "surface,s_over_S,x_over_bx,Tw_norm,Tw_K,h_norm\n")
            s = [r[0] for r in t["rows"]]
            i_stag = min(range(len(s)), key=lambda k: s[k])
            for k, (a, b, tw, h) in enumerate(t["rows"]):
                surf = "PS" if k <= i_stag else "SS"
                tw_s = f"{tw:.4f}" if tw is not None else ""
                twk_s = f"{tw * t['Tref']:.2f}" if tw is not None else ""
                h_s = f"{h:.4f}" if h is not None else ""
                f.write(f"{surf},{a:.4f},{b:.4f},{tw_s},{twk_s},{h_s}\n")
        print(f"  -> {p.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
