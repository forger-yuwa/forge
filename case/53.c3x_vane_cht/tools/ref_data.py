# 孔径 [cm] と助走補正 (case README / 図 6,7)。前方 7 本 φ6.30、次 2 本 φ3.10、最後 φ1.98 mm
HOLE_D_CM = [0.630] * 7 + [0.310] * 2 + [0.198]
HOLE_CR = [1.118] * 7 + [1.056] * 2 + [1.025]


def air_mu(T):
    """Sutherland (空気)。"""
    return 1.716e-5 * (T / 273.15) ** 1.5 * (273.15 + 110.4) / (T + 110.4)


def air_k(T):
    """空気の熱伝導率 [W/mK] (Sutherland 形、Pr=0.71 と cp=1005 から)。"""
    return air_mu(T) * 1005.0 / 0.71


def validate(name):
    err = []
    for (i, tf, tk, red, mlb, mkg) in COOLANT[name]:
        if abs((tf + 459.67) / 1.8 - tk) > 0.05:
            err.append(f"hole {i}: {tf} F != {tk} K")
        if abs(mlb * LB - mkg) > 0.005 * mkg:
            err.append(f"hole {i}: {mlb} lbm/s != {mkg} kg/s")
        D = HOLE_D_CM[i - 1] / 100.0
        re_chk = 4.0 * mkg / (3.141592653589793 * D * air_mu(tk))
        if abs(re_chk / (red * 1e4) - 1.0) > 0.25:
            err.append(f"hole {i}: Re {red*1e4:.3g} vs 4mdot/(pi D mu) {re_chk:.3g}")
    for side, rows in PRESS[name].items():
        s = [r[0] for r in rows]
        if any(s[k] >= s[k + 1] for k in range(len(s) - 1)):
            err.append(f"{side}: s/S が昇順でない")
        for (a, b, p) in rows:
            if not (0.0 < p <= 1.0 and 0.0 <= a <= 1.0 and 0.0 <= b <= 1.0):
                err.append(f"{side}: 範囲外 ({a},{b},{p})")
    print(f"[{name}] pressure PS {len(PRESS[name]['PS'])} / SS {len(PRESS[name]['SS'])} pts, "
          f"coolant {len(COOLANT[name])} holes, {'OK' if not err else 'NG'}")
    for e in err:
        print("   -", e)
    return err


def h_c_from_coolant(name, cr=True):
    r"""公開された冷却剤条件から孔ごとの $h_c$ を作る (**報告 p.22 の式そのもの**)。

    $Nu_D = C_r\,(0.022\,Pr^{0.5}Re_D^{0.8})$ — 「滑らかな管内の乱流」の式に助走区間補正 $C_r$ (図 6/7 の表) を掛ける。
    物性は各孔の平均冷却剤温度で評価する。2026-09-22 まで Dittus-Boelter ($0.023Re^{0.8}Pr^{0.4}$) を使い
    「報告は相関を書いていない」としていたのは見落とし (報告の係数は 0.022·0.71^0.5 = 0.0185、D-B は 0.0201 で 8 % 大きい)。
    """
    out = []
    for (i, tf, tk, red, mlb, mkg) in COOLANT[name]:
        D = HOLE_D_CM[i - 1] / 100.0
        Re = red * 1e4
        Nu = 0.022 * 0.71 ** 0.5 * Re ** 0.8
        h = Nu * air_k(tk) / D
        if cr:
            h *= HOLE_CR[i - 1]
        out.append(dict(hole=i, T_c=tk, Re=Re, D_m=D, h=h))
    return out


def main():
    bad = 0
    for name in PRESS:
        bad += len(validate(name))
        print(f"  h_c from published coolant data ({name}):")
        for r in h_c_from_coolant(name):
            print(f"    hole {r['hole']:2d}  T_c {r['T_c']:6.1f} K  Re {r['Re']:8.3g}  "
                  f"D {r['D_m']*1000:4.2f} mm  ->  h_c {r['h']:7.1f} W/m2K")
    if bad:
        sys.exit("転記の検査に失敗")


if __name__ == "__main__":
    main()
